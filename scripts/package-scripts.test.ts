/**
 * The services' and packages' own scripts, all run by Bun (`bun run gen`, `drift`, the web
 * build, `serve:web`): each writes what it promises, and fails the way it says it does.
 */
import { afterEach, describe, expect, it, mock, spyOn } from "bun:test";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { writeOpenApi } from "../apps/api/scripts/openapi";
import { copyStatic } from "../apps/web/scripts/copy-static";
import { drift } from "../packages/db/scripts/drift";
import { declareMessages } from "../packages/i18n/scripts/declare-messages";
import { exportSchemas } from "../packages/jobs/scripts/export-schemas";

afterEach(() => mock.restore());

const scratch = () => mkdtempSync(join(tmpdir(), "package-scripts-"));
const read = (path: string) => readFileSync(path, "utf8");

describe("apps/api's OpenAPI document", () => {
  it("is written to the file it's given, for version 1 under /api/v1", async () => {
    const file = join(scratch(), "openapi.json");
    await writeOpenApi(file);
    const spec = JSON.parse(read(file)) as { info: { version: string }; servers: unknown };
    expect(spec.info.version).toBe("1");
    expect(spec.servers).toEqual([{ url: "/api/v1" }]);
    expect(writeOpenApi(undefined)).rejects.toThrow("usage: bun scripts/openapi.ts <file>");
  });
});

describe("apps/web's static assets", () => {
  it("are copied next to the standalone server, with public/ when there is one", () => {
    const dir = scratch();
    mkdirSync(join(dir, ".next/static/chunks"), { recursive: true });
    writeFileSync(join(dir, ".next/static/chunks/app.js"), "app");
    copyStatic(dir);
    const server = join(dir, ".next/standalone/apps/web");
    expect(read(join(server, ".next/static/chunks/app.js"))).toBe("app");
    expect(existsSync(join(server, "public"))).toBe(false);
    mkdirSync(join(dir, "public"));
    writeFileSync(join(dir, "public/sw.js"), "sw");
    copyStatic(dir);
    expect(read(join(server, "public/sw.js"))).toBe("sw");
  });
});

describe("packages/i18n's message types", () => {
  it("declare the English catalog with each message as its literal text", () => {
    const dir = scratch();
    writeFileSync(join(dir, "en.json"), '{"email":{"otp":{"expires":"In {minutes} minutes"}}}');
    declareMessages(dir);
    const declared = read(join(dir, "en.d.json.ts"));
    expect(declared).toStartWith("// Generated by scripts/declare-messages.ts");
    expect(declared).toContain('"expires": "In {minutes} minutes"');
    expect(declared).toEndWith("export default messages;\n");
  });
});

describe("packages/jobs' shared schemas", () => {
  it("write what the Python service is generated from, starting empty", () => {
    const dir = scratch();
    mkdirSync(join(dir, "schemas"));
    writeFileSync(join(dir, "schemas/stale.json"), "{}");
    exportSchemas(dir);
    const schemas = readdirSync(join(dir, "schemas"));
    expect(schemas).not.toContain("stale.json");
    expect(schemas).toEqual(
      expect.arrayContaining(["ai_director_plan_job.json", "error_response.json"]),
    );
    const errorResponse = JSON.parse(read(join(dir, "schemas/error_response.json")));
    expect(errorResponse).toMatchObject({ title: "ErrorResponse" });
    for (const file of ["queue-settings.json", "error-codes.json", "events.json"]) {
      expect(existsSync(join(dir, file))).toBe(true);
    }
    expect(read(join(dir, "realtime-channels.json"))).toContain("{id}");
  });
});

describe("packages/db's drift check", () => {
  /** `prisma migrate diff` answering `outputs` in turn (migrations, then the database). */
  const prisma = (...outputs: { status?: number; stdout?: string }[]) => {
    const calls: string[] = [];
    const spawn = (command: string, args: string[]) => {
      calls.push([command, ...args].join(" "));
      const { status = 0, stdout = "" } = outputs.shift() ?? {};
      return { status, stdout, stderr: status ? "prisma failed\n" : "" };
    };
    return { spawn, calls };
  };
  const written = () => {
    const out = spyOn(process.stdout, "write").mockImplementation(() => true);
    const err = spyOn(process.stderr, "write").mockImplementation(() => true);
    return () => [...out.mock.calls, ...err.mock.calls].map(([text]) => String(text)).join("");
  };

  it("passes when both diffs hold only comments", () => {
    const output = written();
    const { spawn, calls } = prisma(
      { stdout: "-- empty\nLoaded Prisma config\n" },
      { stdout: "-- This is an empty migration.\n" },
    );
    expect(drift(spawn)).toBe(0);
    expect(calls).toEqual([
      "bunx prisma migrate diff --from-migrations prisma/migrations --to-schema prisma/schema --script",
      "bunx prisma migrate diff --from-config-datasource --to-schema prisma/schema --script",
    ]);
    expect(output()).toContain("No drift");
  });

  it("fails on any other statement, naming which side drifted", () => {
    const output = written();
    expect(drift(prisma({}, { stdout: 'ALTER TABLE "file" ADD COLUMN "x" TEXT;' }).spawn)).toBe(1);
    expect(output()).toContain('Drift (database vs schema):\n  ALTER TABLE "file"');
  });

  it("stops when prisma fails", () => {
    const output = written();
    expect(() => drift(prisma({ status: 1 }).spawn)).toThrow("prisma migrate diff failed");
    expect(output()).toContain("prisma failed");
  });
});
